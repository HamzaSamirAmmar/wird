// Regenerates the mushaf page index and the Uthmani text asset from Tanzil.
//
//   node packages/quran-data/scripts/generate-quran-data.mjs
//
// Writes:
//   packages/quran-data/src/pageStarts.ts   604 page-start markers (~12 KB, bundled)
//   apps/pwa/public/quran-uthmani.json      6236 ayah texts (~1.3 MB, fetched on demand)
//
// Source: Tanzil.net (https://tanzil.net) — Uthmani text, "Tanzil Quran Text" licence:
// non-commercial redistribution permitted provided the text is unmodified and attributed.
// The text is written out verbatim, byte for byte as delivered.
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const META = 'https://tanzil.net/res/text/metadata/quran-data.xml';
const TEXT = 'https://tanzil.net/pub/download/index.php?quranType=uthmani&outType=txt-2&agree=true';

const TOTAL_SURAHS = 114;
const TOTAL_AYAHS = 6236;
const TOTAL_PAGES = 604;

async function get(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} fetching ${url}`);
  return res.text();
}

const [metaXml, textRaw] = await Promise.all([get(META), get(TEXT)]);

// ── page index ──────────────────────────────────────────────────────────────
const pageStarts = [
  ...metaXml.matchAll(/<page\s+index="(\d+)"\s+sura="(\d+)"\s+aya="(\d+)"\s*\/>/g),
].map((m) => [Number(m[2]), Number(m[3])]);
if (pageStarts.length !== TOTAL_PAGES) {
  throw new Error(`Expected ${TOTAL_PAGES} pages, parsed ${pageStarts.length}`);
}

// ── ayah text ───────────────────────────────────────────────────────────────
const bySurah = Array.from({ length: TOTAL_SURAHS }, () => []);
let count = 0;
for (const line of textRaw.split('\n')) {
  const trimmed = line.trim();
  if (!trimmed || trimmed.startsWith('#')) continue;
  const [s, a, ...rest] = trimmed.split('|');
  const surah = Number(s);
  const ayah = Number(a);
  const text = rest.join('|');
  if (!surah || !ayah || !text) throw new Error(`Unparseable line: ${trimmed.slice(0, 40)}`);
  if (bySurah[surah - 1].length !== ayah - 1) {
    throw new Error(`Out-of-order ayah ${surah}:${ayah}`);
  }
  bySurah[surah - 1].push(text);
  count++;
}
if (count !== TOTAL_AYAHS) throw new Error(`Expected ${TOTAL_AYAHS} ayahs, parsed ${count}`);

// Cross-check the parsed counts against the surah table this package already ships.
const { SURAHS } = await import('../src/surahs.ts');
for (const s of SURAHS) {
  if (bySurah[s.number - 1].length !== s.ayahCount) {
    throw new Error(
      `Surah ${s.number}: table says ${s.ayahCount}, text has ${bySurah[s.number - 1].length}`,
    );
  }
}

const srcDir = new URL('../src/', import.meta.url);
writeFileSync(
  fileURLToPath(new URL('pageStarts.ts', srcDir)),
  `// GENERATED by scripts/generate-quran-data.mjs — do not edit by hand.\n` +
    `// First ayah of each of the ${TOTAL_PAGES} pages of the Mushaf al-Madinah, as [surah, ayah].\n` +
    `// Source: Tanzil.net quran-data.xml\n\n` +
    `export const PAGE_STARTS: readonly (readonly [number, number])[] = ${JSON.stringify(pageStarts)};\n`,
);

const pwaPublic = new URL('../../../apps/pwa/public/', import.meta.url);
mkdirSync(pwaPublic, { recursive: true });
writeFileSync(
  fileURLToPath(new URL('quran-uthmani.json', pwaPublic)),
  JSON.stringify({
    source: 'Tanzil.net — Uthmani',
    licence: 'Tanzil Quran Text, non-commercial redistribution with attribution',
    surahs: bySurah,
  }),
);

console.log(
  `wrote pageStarts.ts (${pageStarts.length} pages) and quran-uthmani.json (${count} ayahs)`,
);
